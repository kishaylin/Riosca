import streamlit as st
import numpy as np
import pandas as pd
import joblib

# Page configuration
st.set_page_config(page_title="Riosca - Irish Stock Exchange Risk Analysis", layout="wide")

# Load model and dataset
@st.cache_resource
def load_resources():
    model = joblib.load("company_risk_model.pkl")
    df = pd.read_csv("irish_stock_exchange_companies.csv")
    return model, df

try:
    model, df = load_resources()
except Exception as e:
    st.error("Please ensure `company_risk_model.pkl` and `irish_stock_exchange_companies.csv` are in your folder!")

st.title("Riosca - Irish Stock Exchange (Euronext Dublin) Financial Risk Analysis")
st.write("Analyse risk profiles and investment recommendations for companies listed on the Irish Stock Exchange. \n *Note that the data was found and generated by AI")

# Create tabs for different modes
tab1, tab2 = st.tabs([" Select Listed Irish Company", " Custom Metrics Simulator"])

with tab1:
    st.subheader("Explore Listed Companies")
    
    # Dropdown menu of Irish companies
    selected_company = st.selectbox("Choose a Company Listed on Euronext Dublin:", df["company_id"].tolist())
    
    # Retrieve row data for selected company
    company_row = df[df["company_id"] == selected_company].iloc[0]
    
    # Display metrics in cards
    col1, col2, col3 = st.columns(3)
    col1.metric("Current Ratio", f"{company_row['current_ratio']:.2f}")
    col1.metric("Debt-to-Equity", f"{company_row['debt_to_equity']:.2f}")
    col2.metric("Return on Equity (ROE)", f"{company_row['return_on_equity']:.1%}")
    col2.metric("Net Profit Margin", f"{company_row['net_profit_margin']:.1%}")
    col3.metric("Cash Flow to Debt", f"{company_row['cash_flow_to_debt']:.2f}")
    col3.metric("Interest Coverage", f"{company_row['interest_coverage_ratio']:.1f}x")
    
    if st.button("Evaluate Company Risk Profile", type="primary"):
        features = np.array([[
            company_row["current_ratio"],
            company_row["debt_to_equity"],
            company_row["return_on_equity"],
            company_row["net_profit_margin"],
            company_row["cash_flow_to_debt"],
            company_row["interest_coverage_ratio"]
        ]])
        
        prediction = model.predict(features)[0]
        probabilities = model.predict_proba(features)[0]
        high_risk_prob = probabilities[1]
        
        st.markdown("---")
        if prediction == 1:
            st.error(f"⚠️ **Model Verdict: High Risk / Distressed** (Risk Score: {high_risk_prob:.1%})")
            st.warning("💡 **Investor Recommendation:** **Avoid / High Risk**. The company displays elevated debt levers or tight interest coverage metrics.")
        else:
            st.success(f"✅ **Model Verdict: Low Risk / Financially Stable** (Confidence: {1 - high_risk_prob:.1%})")
            st.info("💡 **Investor Recommendation:** **Suitable for Investment**. Strong liquidity, profit margins, and interest coverage ratios.")

with tab2:
    st.subheader("Test Custom Metrics")
    
    c1, c2 = st.columns(2)
    with c1:
        current_ratio = st.number_input("Current Ratio", min_value=0.0, max_value=10.0, value=1.5, step=0.1)
        debt_to_equity = st.number_input("Debt to Equity Ratio", min_value=0.0, max_value=10.0, value=1.2, step=0.1)
        return_on_equity = st.number_input("Return on Equity (ROE)", min_value=-1.0, max_value=1.0, value=0.12, step=0.01)

    with c2:
        net_profit_margin = st.number_input("Net Profit Margin", min_value=-1.0, max_value=1.0, value=0.08, step=0.01)
        cash_flow_to_debt = st.number_input("Cash Flow to Debt Ratio", min_value=-1.0, max_value=2.0, value=0.25, step=0.05)
        interest_coverage = st.number_input("Interest Coverage Ratio", min_value=-5.0, max_value=30.0, value=4.5, step=0.5)

    if st.button("Evaluate Custom Inputs", type="primary"):
        features = np.array([[current_ratio, debt_to_equity, return_on_equity, net_profit_margin, cash_flow_to_debt, interest_coverage]])
        prediction = model.predict(features)[0]
        probabilities = model.predict_proba(features)[0]
        high_risk_prob = probabilities[1]
        
        st.markdown("---")
        if prediction == 1:
            st.error(f"⚠️ **Model Verdict: High Risk / Distressed** (Risk Score: {high_risk_prob:.1%})")
        else:
            st.success(f"✅ **Model Verdict: Low Risk / Stable** (Confidence: {1 - high_risk_prob:.1%})")